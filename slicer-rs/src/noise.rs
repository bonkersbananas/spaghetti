const X_NOISE_GEN: i32 = 1619;
const Y_NOISE_GEN: i32 = 31337;
const Z_NOISE_GEN: i32 = 6971;
const SEED_NOISE_GEN: i32 = 1013;
const SHIFT_NOISE_GEN: i32 = 8;

/// A noise as Orca's fuzzy skin sets up libnoise's module.
#[derive(Clone, Copy, Debug)]
pub enum Noise {
    Perlin {
        frequency: f64,
        octaves: i32,
        persistence: f64,
    },
    Billow {
        frequency: f64,
        octaves: i32,
        persistence: f64,
    },
    RidgedMulti {
        frequency: f64,
        octaves: i32,
    },
    /// Displacement 1, distance off.
    Voronoi {
        frequency: f64,
    },
}

impl Noise {
    /// The module's `GetValue`.
    pub fn value(&self, x: f64, y: f64, z: f64) -> f64 {
        match *self {
            Noise::Perlin { frequency, octaves, persistence } => {
                fractal(x, y, z, frequency, octaves, persistence, false)
            }
            Noise::Billow { frequency, octaves, persistence } => {
                fractal(x, y, z, frequency, octaves, persistence, true)
            }
            Noise::RidgedMulti { frequency, octaves } => ridged(x, y, z, frequency, octaves),
            Noise::Voronoi { frequency } => voronoi(x, y, z, frequency),
        }
    }
}

/// libnoise's cell of a coordinate: `(int)x`, one lower for anything not above 0 (0 itself too).
fn cell(x: f64) -> i32 {
    if x > 0.0 { x as i32 } else { x as i32 - 1 }
}

fn s_curve3(a: f64) -> f64 {
    a * a * (3.0 - 2.0 * a)
}

fn lerp(n0: f64, n1: f64, a: f64) -> f64 {
    ((1.0 - a) * n0) + (a * n1)
}

/// `MakeInt32Range`: keeps a coordinate within ±2^30.
fn int32_range(n: f64) -> f64 {
    if n >= 1073741824.0 {
        (2.0 * (n % 1073741824.0)) - 1073741824.0
    } else if n <= -1073741824.0 {
        (2.0 * (n % 1073741824.0)) + 1073741824.0
    } else {
        n
    }
}

fn hash(x: i32, y: i32, z: i32, seed: i32) -> i32 {
    X_NOISE_GEN
        .wrapping_mul(x)
        .wrapping_add(Y_NOISE_GEN.wrapping_mul(y))
        .wrapping_add(Z_NOISE_GEN.wrapping_mul(z))
        .wrapping_add(SEED_NOISE_GEN.wrapping_mul(seed))
}

/// `GradientNoise3D`.
fn gradient_noise(fx: f64, fy: f64, fz: f64, ix: i32, iy: i32, iz: i32, seed: i32) -> f64 {
    let mut index = hash(ix, iy, iz, seed);
    index ^= index >> SHIFT_NOISE_GEN;
    let g = &VECTORS[(index & 0xff) as usize];
    let (px, py, pz) = (fx - ix as f64, fy - iy as f64, fz - iz as f64);
    ((g[0] * px) + (g[1] * py) + (g[2] * pz)) * 2.12
}

/// `GradientCoherentNoise3D` at standard quality.
fn gradient_coherent(x: f64, y: f64, z: f64, seed: i32) -> f64 {
    let (x0, y0, z0) = (cell(x), cell(y), cell(z));
    let (x1, y1, z1) = (x0.wrapping_add(1), y0.wrapping_add(1), z0.wrapping_add(1));
    let xs = s_curve3(x - x0 as f64);
    let ys = s_curve3(y - y0 as f64);
    let zs = s_curve3(z - z0 as f64);
    let g = |ix, iy, iz| gradient_noise(x, y, z, ix, iy, iz, seed);
    let ix0 = lerp(g(x0, y0, z0), g(x1, y0, z0), xs);
    let ix1 = lerp(g(x0, y1, z0), g(x1, y1, z0), xs);
    let iy0 = lerp(ix0, ix1, ys);
    let ix0 = lerp(g(x0, y0, z1), g(x1, y0, z1), xs);
    let ix1 = lerp(g(x0, y1, z1), g(x1, y1, z1), xs);
    let iy1 = lerp(ix0, ix1, ys);
    lerp(iy0, iy1, zs)
}

/// `IntValueNoise3D` as Orca's own build has it: libnoise masks the result to 31 bits, but GCC, taking the signed
/// overflow before it as impossible, drops the mask (OrcaSlicer 2.5.1's `noise::IntValueNoise3D`: `madd` and `ret`),
/// so it wraps to any 32-bit value, negative too.
fn int_value_noise(x: i32, y: i32, z: i32, seed: i32) -> i32 {
    let mut n = hash(x, y, z, seed) & 0x7fffffff;
    n ^= n >> 13;
    n.wrapping_mul(n.wrapping_mul(n).wrapping_mul(60493).wrapping_add(19990303)).wrapping_add(1376312589)
}

/// `ValueNoise3D`: from −1 to 1 in libnoise, from −1 to 3 in Orca's build (`int_value_noise`).
fn value_noise(x: i32, y: i32, z: i32, seed: i32) -> f64 {
    1.0 - (int_value_noise(x, y, z, seed) as f64 / 1073741824.0)
}

/// `Perlin::GetValue`, or with `billow` `Billow::GetValue` (each octave's signal folded, `2|s| − 1`, and 0.5 added).
fn fractal(x: f64, y: f64, z: f64, frequency: f64, octaves: i32, persistence: f64, billow: bool) -> f64 {
    let (mut x, mut y, mut z) = (x * frequency, y * frequency, z * frequency);
    let mut value = 0.0;
    let mut weight = 1.0;
    for octave in 0..octaves {
        let mut signal = gradient_coherent(int32_range(x), int32_range(y), int32_range(z), octave);
        if billow {
            signal = 2.0 * signal.abs() - 1.0;
        }
        value += signal * weight;
        x *= 2.0;
        y *= 2.0;
        z *= 2.0;
        weight *= persistence;
    }
    if billow { value + 0.5 } else { value }
}

/// `RidgedMulti::GetValue`, its spectral weights for lacunarity 2 (`pow(2^i, −1)`, exactly 2^−i).
fn ridged(x: f64, y: f64, z: f64, frequency: f64, octaves: i32) -> f64 {
    let (mut x, mut y, mut z) = (x * frequency, y * frequency, z * frequency);
    let (mut value, mut weight, mut spectral) = (0.0, 1.0, 1.0);
    for octave in 0..octaves.min(30) {
        let mut signal = gradient_coherent(int32_range(x), int32_range(y), int32_range(z), octave & 0x7fffffff);
        signal = 1.0 - signal.abs();
        signal *= signal;
        signal *= weight;
        weight = (signal * 2.0).clamp(0.0, 1.0);
        value += signal * spectral;
        spectral *= 0.5;
        x *= 2.0;
        y *= 2.0;
        z *= 2.0;
    }
    (value * 1.25) - 1.0
}

/// `Voronoi::GetValue` with displacement 1 and no distance: the value of the cell whose seed point is nearest.
fn voronoi(x: f64, y: f64, z: f64, frequency: f64) -> f64 {
    let (x, y, z) = (x * frequency, y * frequency, z * frequency);
    let (xi, yi, zi) = (cell(x), cell(y), cell(z));
    let mut min = 2147483647.0;
    let mut nearest = (0.0, 0.0, 0.0);
    for zc in zi - 2..=zi + 2 {
        for yc in yi - 2..=yi + 2 {
            for xc in xi - 2..=xi + 2 {
                let px = xc as f64 + value_noise(xc, yc, zc, 0);
                let py = yc as f64 + value_noise(xc, yc, zc, 1);
                let pz = zc as f64 + value_noise(xc, yc, zc, 2);
                let (dx, dy, dz) = (px - x, py - y, pz - z);
                let d = dx * dx + dy * dy + dz * dz;
                if d < min {
                    min = d;
                    nearest = (px, py, pz);
                }
            }
        }
    }
    value_noise(nearest.0.floor() as i32, nearest.1.floor() as i32, nearest.2.floor() as i32, 0)
}

