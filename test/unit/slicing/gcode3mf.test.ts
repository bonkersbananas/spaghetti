import { strFromU8, strToU8, unzipSync, zipSync } from "fflate";
import { describe, expect, it } from "vitest";
import { packGcode3mf, summarizeGcode } from "../../../src/shared/slicing/gcode3mf.ts";
import { md5Hex } from "../../../src/shared/slicing/md5.ts";
import { settingsFromFile, slicerName } from "../../../src/shared/threemf/prefill.ts";
import { readThreeMf } from "../../../src/shared/threemf/read.ts";
import { bambuStudioProblems } from "./bambu-rules.ts";

const PNG = new Uint8Array([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 7, 7, 7]);

/** The few lines of an Orca G-code file the app reads: its header and its footer. */
const GCODE = strToU8(
  [
    "; HEADER_BLOCK_START",
    "; generated by OrcaSlicer 2.5.0-dev on 2026-11-13 at 01:00:00",
    "; total layer number: 100",
    "; model label id: 22,23",
    "; model printing time: 12m 3s; total estimated time: 1h 2m 3s",
    "; HEADER_BLOCK_END",
    "G28",
    "G1 X10 Y10 Z0.2 E1",
    "; filament used [mm] = 1210.55, 40.00",
    "; filament used [g] = 3.61, 0.12",
    "",
  ].join("\n"),
);

const settings = {
  printer_model: "Bambu Lab X2D",
  printer_settings_id: "Bambu Lab X2D 0.4 nozzle",
  extruder_type: ["Direct Drive", "Bowden"],
  extruder_variant_list: ["Direct Drive Standard,Direct Drive High Flow", "Bowden Standard,Bowden High Flow"],
  nozzle_diameter: ["0.4", "0.4"],
  layer_height: "0.2",
  sparse_infill_density: "15%",
  wall_loops: "2",
  enable_support: "0",
  curr_bed_type: "Textured PEI Plate",
  print_settings_id: "0.20mm Standard @BBL X2D",
  filament_diameter: ["1.75", "1.75"],
  filament_type: ["PLA", "PETG"],
  filament_colour: ["#F2754E", "#4F7FC7"],
  filament_settings_id: ["Bambu PLA Basic @BBL X2D 0.4 nozzle", "Generic PETG @BBL X2D 0.4 nozzle"],
  nozzle_temperature: ["220", "250"],
  textured_plate_temp: ["55", "70"],
};

function packed() {
  return packGcode3mf({
    gcode: GCODE,
    thumbnail: PNG,
    seconds: 3723,
    grams: 3.73,
    layers: 100,
    objects: [
      { name: "cube.stl", box: { min: [118, 118, 0], max: [138, 138, 20] }, id: 22 },
      { name: "lid & cap.stl", box: { min: [90, 100, 0], max: [110, 120, 4] }, id: 23 },
    ],
    settings,
    filaments: [
      { type: "PLA", colour: "#F2754E", usedGrams: 3.61, usedMeters: 1.21 },
      { type: "PETG", colour: "#4F7FC7", usedGrams: 0.12, usedMeters: 0.04 },
    ],
    slicer: { name: "OrcaSlicer", version: "2.5.0-dev" },
    title: "cube.stl",
  });
}

describe("packGcode3mf", () => {
  it("lays the file out as Orca's own export does, with the G-code's MD5 and the plate picture", () => {
    const files = unzipSync(packed());
    expect(Object.keys(files).sort()).toEqual([
      "3D/3dmodel.model",
      "Metadata/_rels/model_settings.config.rels",
      "Metadata/filament_sequence.json",
      "Metadata/model_settings.config",
      "Metadata/plate_1.gcode",
      "Metadata/plate_1.gcode.md5",
      "Metadata/plate_1.json",
      "Metadata/plate_1.png",
      "Metadata/project_settings.config",
      "Metadata/slice_info.config",
      "[Content_Types].xml",
      "_rels/.rels",
    ]);
    expect(files["Metadata/plate_1.gcode"]).toEqual(GCODE);
    expect(strFromU8(files["Metadata/plate_1.gcode.md5"] ?? new Uint8Array())).toBe(md5Hex(GCODE));
    expect(JSON.parse(strFromU8(files["Metadata/project_settings.config"] ?? new Uint8Array()))).toEqual({
      ...settings,
      extruder_variant_list: undefined,
      filament_ids: ["GFA00", "GFG99"],
    });
    expect(JSON.parse(strFromU8(files["Metadata/plate_1.json"] ?? new Uint8Array()))).toMatchObject({
      bed_type: "textured_plate",
      filament_colors: ["#F2754E", "#4F7FC7"],
      nozzle_diameter: 0.4,
    });
  });

  it("holds to what Bambu Studio's reader needs to open it as a sliced plate (not 'no geometry data')", () => {
    expect(bambuStudioProblems(packed())).toEqual([]);
    // The rule has teeth: Orca's own name as the generator is what failed in Bambu Studio.
    const files = unzipSync(packed());
    const model = strFromU8(files["3D/3dmodel.model"] ?? new Uint8Array()).replace("BambuStudio-", "OrcaSlicer-");
    files["3D/3dmodel.model"] = strToU8(model);
    expect(bambuStudioProblems(zipSync(files))).toEqual([expect.stringContaining('not "BambuStudio-<version>"')]);
  });

  it("breaks each rule of Bambu Studio's reader it was written from, and the rules notice", () => {
    const tamper = (change: (files: Record<string, Uint8Array>) => void) => {
      const files = unzipSync(packed());
      change(files);
      return bambuStudioProblems(zipSync(files));
    };
    const edit = (files: Record<string, Uint8Array>, name: string, change: (text: string) => string) => {
      files[name] = strToU8(change(strFromU8(files[name] ?? new Uint8Array())));
    };
    expect(
      tamper((f) =>
        edit(f, "Metadata/slice_info.config", (t) =>
          t.replace('key="printer_model_id" value="N6"', 'key="printer_model_id" value=""'),
        ),
      ),
    ).toEqual([expect.stringContaining("printer_model_id")]);
    expect(
      tamper((f) =>
        edit(f, "Metadata/slice_info.config", (t) => t.replace(/ tray_info_idx="GFA00"/, ' tray_info_idx=""')),
      ),
    ).toEqual([expect.stringContaining("tray_info_idx"), expect.stringContaining("tray_info_idx")]);
    expect(
      tamper((f) => edit(f, "Metadata/slice_info.config", (t) => t.replace('identify_id="22"', 'identify_id="1"'))),
    ).not.toEqual([]);
    expect(
      tamper((f) =>
        edit(f, "Metadata/project_settings.config", (t) => t.replace('"Bambu Lab X2D 0.4 nozzle"', '"My printer"')),
      ),
    ).toEqual([expect.stringContaining("printer_settings_id")]);
    expect(
      tamper((f) =>
        edit(f, "Metadata/project_settings.config", (t) =>
          t.replace(/"filament_ids"/, '"extruder_variant_list": ["a"],\n"filament_ids"'),
        ),
      ),
    ).toEqual([expect.stringContaining("extruder_variant_list")]);
    expect(tamper((f) => edit(f, "Metadata/plate_1.gcode.md5", (t) => t.toLowerCase()))).toEqual([
      expect.stringContaining("upper case"),
    ]);
    expect(tamper((f) => delete f["Metadata/plate_1.png"])).toEqual([expect.stringContaining("plate_1.png")]);
    // Zip order matters: slice_info read before model_settings finds no plate to put its filaments in.
    const files = unzipSync(packed());
    const { "Metadata/slice_info.config": sliceInfo, ...rest } = files;
    expect(
      bambuStudioProblems(zipSync({ "Metadata/slice_info.config": sliceInfo as Uint8Array, ...rest })),
    ).toContainEqual(expect.stringContaining("comes before"));
  });

  it("is read by the app's own reader as a sliced file: plate, estimate, weight, objects, filaments and settings", () => {
    const result = readThreeMf(packed());
    expect(result.kind).toBe("sliced");
    expect(slicerName(result)).toBe("OrcaSlicer 2.5.0-dev");
    expect(result.plates).toHaveLength(1);
    const plate = result.plates[0];
    expect(plate).toMatchObject({
      index: 1,
      predictedSeconds: 3723,
      weightGrams: 3.73,
      bedType: "Textured PEI Plate",
      objects: [{ name: "cube.stl" }, { name: "lid & cap.stl" }],
    });
    expect(plate?.thumbnail?.bytes).toEqual(PNG);
    expect(plate?.filaments.map((filament) => [filament.type, filament.colorHex, filament.usedGrams])).toEqual([
      ["PLA", "#f2754e", 3.61],
      ["PETG", "#4f7fc7", 0.12],
    ]);
    expect(settingsFromFile(result, 1)).toMatchObject({
      estimatedMinutes: 62,
      weightGrams: 3.7,
      layerHeight: 0.2,
      infillDensity: 15,
      wallLoops: 2,
      supportEnabled: false,
      bedType: "Textured PEI Plate",
      processPreset: "0.20mm Standard @BBL X2D",
    });
  });
});

describe("summarizeGcode", () => {
  it("reads the estimate, the layers and each filament's use from the header and footer", () => {
    expect(summarizeGcode(GCODE)).toEqual({
      seconds: 3723,
      layers: 100,
      labels: [22, 23],
      grams: [3.61, 0.12],
      millimetres: [1210.55, 40],
    });
    expect(summarizeGcode(strToU8("G28\n"))).toEqual({
      seconds: null,
      layers: null,
      labels: [],
      grams: [],
      millimetres: [],
    });
  });
});

describe("md5Hex", () => {
  it("is the MD5 Bambu's printers check a plate's G-code against, in capitals", () => {
    expect(md5Hex(new Uint8Array())).toBe("D41D8CD98F00B204E9800998ECF8427E");
    expect(md5Hex(strToU8("abc"))).toBe("900150983CD24FB0D6963F7D28E17F72");
    expect(md5Hex(strToU8("The quick brown fox jumps over the lazy dog"))).toBe("9E107D9D372BB6826BD81D3542A419D6");
    // Across blocks: 1 000 000 'a's.
    expect(md5Hex(new Uint8Array(1_000_000).fill(0x61))).toBe("7707D6AE4E027C70EEA2A935C2296F21");
  });
});
